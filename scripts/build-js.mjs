/**
 * Script build.
 *
 * Joins the plain ES modules in resources/js/ into the two files a consumer
 * can load:
 *
 *   dist/blade-ui.js         ES module, readable. `export default` is the
 *                            Alpine plugin, for a host that bundles Alpine:
 *                            `Alpine.plugin(bladeUi)`.
 *   dist/blade-ui.global.js  Classic script, comments and indentation stripped.
 *                            Registers itself on `alpine:init`. This is what
 *                            ds::scripts links (and inlines, with `inline`).
 *
 * Two files because one cannot be both. A classic script may not contain
 * `export`, and a module script is always deferred, so it would run AFTER a
 * non-deferred Alpine or Livewire script that sits above it in the page and
 * register too late to matter.
 *
 * No bundler dependency. This is about sixty lines because the module shapes it
 * accepts are deliberately few, and anything else is refused by name rather
 * than passed through half-understood:
 *
 *   import { a, b } from './x.js';     import x from './x.js';
 *   export function name() {}          export default function name() {}
 *   export const name = …;
 *
 * Each module is wrapped in its own function, so two behaviour files can both
 * have a helper called `write` without one silently replacing the other.
 *
 *   node scripts/build-js.mjs
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gzipSync } from 'node:zlib';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'resources/js');
const DIST = join(ROOT, 'dist');

const banner = (what) =>
    `/**\n * ${what}\n *\n * GENERATED by scripts/build-js.mjs from resources/js/ — do not edit.\n */\n`;

const IMPORT = /^import\s+(?:\{([^}]*)\}|([A-Za-z_$][\w$]*))\s+from\s+'([^']+)';?\s*$/;
const EXPORT_FN = /^export\s+(default\s+)?(async\s+)?function\s+([A-Za-z_$][\w$]*)/;
const EXPORT_CONST = /^export\s+const\s+([A-Za-z_$][\w$]*)/;

/** Read one module and everything it imports, dependencies first. */
async function collect(file, seen = new Map()) {
    if (seen.has(file)) return seen;

    const source = await readFile(file, 'utf8');
    const name = relative(SRC, file);
    const out = [];
    const exported = [];
    let defaultName = null;
    const deps = [];

    for (const [index, line] of source.split('\n').entries()) {
        const where = `${name}:${index + 1}`;

        // The comment stripper below is line-based, which is only safe if no
        // string spans lines. Plain quotes cannot; a template literal can.
        if ((line.match(/`/g) ?? []).length % 2) {
            throw new Error(`${where}: a template literal that spans lines — keep each one on a single line`);
        }

        const imp = line.match(IMPORT);
        if (imp) {
            const [, named, single, spec] = imp;
            if (!spec.startsWith('./') && !spec.startsWith('../')) {
                throw new Error(`${where}: imports '${spec}' — the script has no dependencies, only relative files`);
            }
            const target = fileURLToPath(new URL(spec, pathToFileURL(file)));
            deps.push(target);
            const id = moduleId(target);
            out.push(named
                ? `const {${named}} = ${id};`
                : `const ${single} = ${id}.default;`);
            continue;
        }
        if (/^\s*import\b/.test(line)) throw new Error(`${where}: an import this build does not understand`);

        const fn = line.match(EXPORT_FN);
        if (fn) {
            const [, isDefault, , fnName] = fn;
            if (isDefault) defaultName = fnName;
            else exported.push(fnName);
            out.push(line.replace(/^export\s+(default\s+)?/, ''));
            continue;
        }

        const constant = line.match(EXPORT_CONST);
        if (constant) {
            exported.push(constant[1]);
            out.push(line.replace(/^export\s+/, ''));
            continue;
        }
        if (/^\s*export\b/.test(line)) throw new Error(`${where}: an export this build does not understand`);

        out.push(line);
    }

    for (const dep of deps) await collect(dep, seen);

    const members = [...exported, ...(defaultName ? [`default: ${defaultName}`] : [])];
    seen.set(file, {
        name,
        id: moduleId(file),
        body: out.join('\n').trim(),
        returns: members.length ? `return { ${members.join(', ')} };` : 'return {};',
    });

    return seen;
}

function moduleId(file) {
    return '__ds_' + relative(SRC, file).replace(/\.js$/, '').replace(/[^\w]/g, '_');
}

function wrap(mod) {
    const body = mod.body.split('\n').map((l) => (l ? `    ${l}` : l)).join('\n');
    return `// ${mod.name}\nconst ${mod.id} = (() => {\n${body}\n\n    ${mod.returns}\n})();`;
}

/**
 * Whole-line comments, blank lines and indentation only. A trailing `// note`
 * after code is left alone, because telling it apart from `//` inside a string
 * needs a tokenizer, and the multi-line template literal check above is what
 * makes the whole-line case safe.
 *
 * The same check is what makes dropping indentation safe: no string or literal
 * spans a line, so a line's leading whitespace is never inside one. It was a
 * quarter of the file once the batch-02 behaviours arrived, and this is the
 * file every page downloads.
 */
function stripComments(code) {
    const out = [];
    let inBlock = false;
    for (const line of code.split('\n')) {
        const t = line.trim();
        if (inBlock) {
            if (t.includes('*/')) inBlock = false;
            continue;
        }
        if (t.startsWith('/*')) {
            if (!t.includes('*/')) inBlock = true;
            else if (t.slice(t.indexOf('*/') + 2).trim()) {
                throw new Error(`code after a block comment on one line would be stripped with it: ${t}`);
            }
            continue;
        }
        if (t.startsWith('//') || t === '') continue;
        out.push(line.trimStart());
    }
    return out.join('\n');
}

/**
 * What a page downloads: the classic file as it stands, and gzipped at the
 * level a server's default compression gets close to. In kB of 1,024 bytes.
 * docs/getting-started.md states both ("about N kB (M kB compressed)"), and
 * test-js.mjs holds that sentence to these, because it said 18 kB for four
 * batches while the file grew past 70.
 */
export function sizes(code) {
    const bytes = Buffer.from(code);
    return {
        raw: bytes.length / 1024,
        compressed: gzipSync(bytes, { level: 9 }).length / 1024,
    };
}

/** Both outputs, as strings. test-js.mjs compares them against dist/. */
export async function bundle() {
    const plugin = [...(await collect(join(SRC, 'blade-ui.js'))).values()];
    const global = [...(await collect(join(SRC, 'global.js'))).values()];

    const esm = `${banner('Shipbytes Blade UI: the Alpine plugin, as an ES module.')}
${plugin.map(wrap).join('\n\n')}

export default ${plugin.at(-1).id}.default;
`;

    const classic = `${banner('Shipbytes Blade UI: the classic script that ds::scripts loads.')}(function () {
'use strict';
${stripComments(global.map(wrap).join('\n'))}
})();
`;

    // `<x-ds::scripts inline />` writes this into a script element, so the
    // content must not be able to end it.
    for (const bad of ['</script', '<!--', '<script']) {
        if (classic.toLowerCase().includes(bad)) {
            throw new Error(`dist/blade-ui.global.js contains "${bad}", which breaks out of the inline script element`);
        }
    }

    return { esm, classic };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
    const { esm, classic } = await bundle();
    await mkdir(DIST, { recursive: true });
    await writeFile(join(DIST, 'blade-ui.js'), esm);
    await writeFile(join(DIST, 'blade-ui.global.js'), classic);

    console.log('built the script:');
    console.log(`  → dist/blade-ui.js         ${(esm.length / 1024).toFixed(1)} kB (ES module, the Alpine plugin)`);
    const served = sizes(classic);
    console.log(`  → dist/blade-ui.global.js  ${served.raw.toFixed(1)} kB, ${served.compressed.toFixed(1)} kB gzipped (classic, served by ds::scripts)`);
}
